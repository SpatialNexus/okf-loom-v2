def sha256_hex(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def sri_sha384(data: bytes) -> str:
    return "sha384-" + base64.b64encode(hashlib.sha384(data).digest()).decode("ascii")


def _safe_rel(rel: str) -> PurePosixPath:
    if not isinstance(rel, str) or not rel or "\\" in rel or "\x00" in rel:
        raise VendorIntegrityError(f"invalid vendored path: {rel!r}")
    path = PurePosixPath(rel)
    if path.is_absolute() or any(part in ("", ".", "..") for part in path.parts):
        raise VendorIntegrityError(f"vendored path escapes the vendor folder: {rel!r}")
    return path


_NOFOLLOW = getattr(os, "O_NOFOLLOW", 0)
_CLOEXEC = getattr(os, "O_CLOEXEC", 0)
_DIRECTORY = getattr(os, "O_DIRECTORY", 0)
# Descriptor-relative no-follow reads need dir_fd support (POSIX). Elsewhere
# the per-component lstat walk below is the (check-then-open) fallback.
_DIR_FD_READS = bool(_NOFOLLOW and _DIRECTORY and os.open in os.supports_dir_fd
                     and os.stat in os.supports_dir_fd)


class VendorTree:
    """No-follow reader pinned to ONE vendor-root directory.

    The root itself must be a real directory (never a symlink). With dir_fd
    support it is opened once, ``O_DIRECTORY | O_NOFOLLOW``, and checked to be
    the inode that was inspected; every later read walks from that descriptor
    with no-follow descriptors, so the lock and the files it describes come
    from the same tree even if a path is swapped concurrently.
    """

    def __init__(self, root: Path | None = None):
        self.root = Path(root) if root is not None else VENDOR_ROOT
        self._fd: int | None = None
        try:
            info = os.lstat(self.root)
        except OSError as exc:
            raise VendorIntegrityError(f"vendor folder missing: {self.root}") from exc
        if stat.S_ISLNK(info.st_mode):
            raise VendorIntegrityError(f"vendor folder is a symlink: {self.root}")
        if not stat.S_ISDIR(info.st_mode):
            raise VendorIntegrityError(f"vendor folder is not a directory: {self.root}")
        if _DIR_FD_READS:
            try:
                fd = os.open(self.root, os.O_RDONLY | _DIRECTORY | _NOFOLLOW | _CLOEXEC)
            except OSError as exc:
                raise VendorIntegrityError(f"vendor folder changed while opening: {self.root}") from exc
            opened = os.fstat(fd)
            if (opened.st_dev, opened.st_ino) != (info.st_dev, info.st_ino) \
                    or not stat.S_ISDIR(opened.st_mode):
                os.close(fd)
                raise VendorIntegrityError(f"vendor folder changed while opening: {self.root}")
            self._fd = fd

    def __enter__(self) -> "VendorTree":
        return self

    def __exit__(self, *exc: object) -> None:
        self.close()

    def close(self) -> None:
        if self._fd is not None:
            os.close(self._fd)
            self._fd = None

    def read(self, rel: str) -> bytes:
        """Read one file below the root, refusing symlinks and non-files."""
        path = _safe_rel(rel)
        if self._fd is None:
            return self._read_by_path(rel, path)
        opened: list[int] = []
        dir_fd = self._fd
        try:
            for part in path.parts[:-1]:
                self._lstat_at(part, dir_fd, rel, want_dir=True)
                try:
                    dir_fd = os.open(part, os.O_RDONLY | _DIRECTORY | _NOFOLLOW | _CLOEXEC, dir_fd=dir_fd)
                except OSError as exc:
                    raise VendorIntegrityError(f"vendored path changed while reading: {rel}") from exc
                opened.append(dir_fd)
            name = path.parts[-1]
            self._lstat_at(name, dir_fd, rel, want_dir=False)
            try:
                # O_NONBLOCK: a FIFO swapped in after the check cannot hang the read.
                fd = os.open(name, os.O_RDONLY | _NOFOLLOW | _CLOEXEC | getattr(os, "O_NONBLOCK", 0),
                             dir_fd=dir_fd)
            except OSError as exc:
                raise VendorIntegrityError(f"vendored path changed while reading: {rel}") from exc
            with os.fdopen(fd, "rb") as handle:
                if not stat.S_ISREG(os.fstat(handle.fileno()).st_mode):
                    raise VendorIntegrityError(f"vendored path is not a regular file: {rel}")
                return handle.read()
        finally:
            for fd in reversed(opened):
                os.close(fd)

    @staticmethod
    def _lstat_at(name: str, dir_fd: int, rel: str, *, want_dir: bool) -> None:
        try:
            info = os.stat(name, dir_fd=dir_fd, follow_symlinks=False)
        except OSError as exc:
            raise VendorIntegrityError(f"vendored file missing: {rel}") from exc
        if stat.S_ISLNK(info.st_mode):
            raise VendorIntegrityError(f"vendored path is a symlink: {rel}")
        if want_dir and not stat.S_ISDIR(info.st_mode):
            raise VendorIntegrityError(f"vendored path is not a directory: {rel}")
        if not want_dir and not stat.S_ISREG(info.st_mode):
            raise VendorIntegrityError(f"vendored path is not a regular file: {rel}")

    def _read_by_path(self, rel: str, path: PurePosixPath) -> bytes:
        current = self.root
        for part in path.parts:
            current = current / part
            try:
                info = os.lstat(current)
            except OSError as exc:
                raise VendorIntegrityError(f"vendored file missing: {rel}") from exc
            if stat.S_ISLNK(info.st_mode):
                raise VendorIntegrityError(f"vendored path is a symlink: {rel}")
        if not stat.S_ISREG(info.st_mode):
            raise VendorIntegrityError(f"vendored path is not a regular file: {rel}")
        fd = os.open(current, os.O_RDONLY | _NOFOLLOW | getattr(os, "O_BINARY", 0))
        with os.fdopen(fd, "rb") as handle:
            return handle.read()


def read_vendor_bytes(rel: str, root: Path | None = None) -> bytes:
    """Read one file below the vendor root, refusing symlinks and non-files."""
    with VendorTree(root) as tree:
        return tree.read(rel)


def load_lock(root: Path | None = None) -> dict[str, Any]:
    with VendorTree(root) as tree:
        return _parse_lock(tree.read(LOCK_NAME))


def _parse_lock(raw: bytes) -> dict[str, Any]:
    try:
        lock = json.loads(raw.decode("utf-8"))
    except (UnicodeDecodeError, ValueError) as exc:
        raise VendorIntegrityError("vendor lock is not valid JSON") from exc
    if not isinstance(lock, dict) or lock.get("schema") != 1 or not isinstance(lock.get("packages"), list) \
            or not isinstance(lock.get("auxiliary", []), list):
        raise VendorIntegrityError("vendor lock has an unsupported schema")
    return lock


def auxiliary_files(lock: dict[str, Any]) -> list[dict[str, Any]]:
    """The lock's auxiliary manifest, validated for shape and required entries."""
    entries = lock.get("auxiliary")
    if not isinstance(entries, list):
        raise VendorIntegrityError("vendor lock has no auxiliary manifest")
    seen: dict[str, str] = {}
    for entry in entries:
        if not isinstance(entry, dict):
            raise VendorIntegrityError("vendor lock auxiliary entry is not an object")
        dest = str(_safe_rel(entry.get("dest", "")))
        role = entry.get("role")
        if role not in AUXILIARY_ROLES:
            raise VendorIntegrityError(f"vendor lock auxiliary entry has an unknown role: {dest}")
        if dest in seen:
            raise VendorIntegrityError(f"vendored path listed twice: {dest}")
        seen[dest] = role
    for dest, role in REQUIRED_AUXILIARY.items():
        if seen.get(dest) != role:
            raise VendorIntegrityError(f"vendor lock does not lock the auxiliary file {dest}")
    return entries


def lock_files(lock: dict[str, Any]) -> list[dict[str, Any]]:
    """Every vendored file entry of the lock, in lock order."""
    out: list[dict[str, Any]] = []
    for package in lock["packages"]:
        for entry in package.get("files", []):
            out.append(entry)
    return out


def _check_entry(entry: dict[str, Any], data: bytes) -> None:
    dest = entry["dest"]
    if len(data) != entry.get("size"):
        raise VendorIntegrityError(f"vendored file size mismatch: {dest}")
    if sha256_hex(data) != entry.get("sha256"):
        raise VendorIntegrityError(f"vendored file sha256 mismatch: {dest}")
    if entry.get("sha384") is not None and sri_sha384(data) != entry["sha384"]:
        raise VendorIntegrityError(f"vendored file sha384 mismatch: {dest}")


def source_sri_pins() -> dict[str, str]:
    """CDN URL -> SRI value as pinned in the code (graph chain + renderers.js)."""
    from .. import render  # lazy: render imports this module
    from .assets import _BUILTIN_STATIC

    pins: dict[str, str] = {}
    for src, integrity in re.findall(
            r'<script src="([^"]+)" integrity="([^"]+)"', render._CDN_SCRIPTS):
        pins[src] = integrity
    renderers = (_BUILTIN_STATIC / "renderers.js").read_text(encoding="utf-8")
    for url, integrity in re.findall(
            r'(?:href|src): "(https://cdn\.jsdelivr\.net/[^"]+)",\s*integrity: "([^"]+)"', renderers):
        pins[url] = integrity
    return pins


def cdn_graph_chain() -> list[str]:
    """The CDN graph-chain URLs in load order (``render._CDN_SCRIPTS``)."""
    from .. import render
    return re.findall(r'<script src="([^"]+)"', render._CDN_SCRIPTS)


