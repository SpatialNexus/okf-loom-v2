@dataclass(frozen=True)
class OfflineAssets:
    """Verified offline payload for one build (constructed by :func:`load_offline_assets`)."""

    files: dict[str, bytes]
    """Output files below ``__static/vendor/`` (vendor-relative path -> bytes)."""
    graph_chain: tuple[str, ...]
    """Vendor-relative graph scripts, in the CDN chain's order."""
    notices: str
    licenses: tuple[tuple[str, str], ...] = field(default_factory=tuple)
    extra_notices: tuple[tuple[str, str], ...] = field(default_factory=tuple)
    """Further locked ``notices`` auxiliary files: (vendor-relative path, text)."""

    # -- static / SPA ------------------------------------------------------
    def static_files(self) -> dict[str, bytes]:
        return dict(self.files)

    def graph_scripts(self, static_prefix: str) -> str:
        return "\n".join(
            f'<script src="{static_prefix}/{STATIC_VENDOR_DIR}/{rel}"></script>'
            for rel in self.graph_chain)

    def finalize_page(self, html: str) -> str:
        """Swap the page CSP for the offline one and add the asset bootstrap."""
        head_end = html.find("</head>")
        meta = f'<meta http-equiv="Content-Security-Policy" content="{CDN_PAGE_CSP}">'
        at = html.find(meta)
        if head_end < 0 or at < 0 or at > head_end:
            raise OfflineAssetsError("offline assets: a page does not carry the built-in CSP")
        html = (html[:at]
                + f'<meta http-equiv="Content-Security-Policy" content="{OFFLINE_PAGE_CSP}">'
                + html[at + len(meta):])
        return html.replace("</head>", _bootstrap("files") + "</head>", 1)

    # -- single file ---------------------------------------------------------
    def single_file_template(self, template: str) -> str:
        meta = f'<meta http-equiv="Content-Security-Policy" content="{CDN_SINGLE_FILE_CSP}">'
        if template.count(meta) != 1:
            raise OfflineAssetsError("offline assets: the single-file template CSP is not the built-in one")
        return template.replace(
            meta, f'<meta http-equiv="Content-Security-Policy" content="{OFFLINE_SINGLE_FILE_CSP}">', 1)

    def single_file_head(self, needs: set[str]) -> str:
        """Carriers, graph-chain injector, bootstrap and notices for ``<head>``."""
        from ..render import _json_for_script

        out = [_bootstrap("inline")]
        chain_ids = []
        for index, rel in enumerate(self.graph_chain):
            carrier = f"okf-vendor-graph-{index}"
            chain_ids.append(carrier)
            out.append(_carrier(carrier, self.files[rel], _json_for_script))
        # Classic, in-order execution of the graph chain before graph.js runs.
        out.append(
            "<script>(function(){var ids=" + json.dumps(chain_ids) + ";"
            "for(var i=0;i<ids.length;i++){var el=document.head&&document.head.querySelector("
            "'script[type=\"application/json\"]#'+ids[i]);"
            "if(!el)return;var code;try{code=JSON.parse(el.textContent);}catch(e){return;}"
            "var s=document.createElement(\"script\");s.setAttribute(\"data-okf-vendor\",ids[i]);"
            "s.text=code;document.head.appendChild(s);}})();</script>")
        for need, keys in _SINGLE_CARRIER_NEEDS.items():
            if need not in needs:
                continue
            for key in keys:
                path, carrier = RENDERER_ASSETS[key]
                rel = path[len(STATIC_VENDOR_DIR) + 1:]
                out.append(_carrier(carrier, self.files[rel], _json_for_script))
        out.append(_notices_block(self.notices, self.licenses, self.extra_notices))
        return "\n".join(out) + "\n"


def _bootstrap(delivery: str) -> str:
    payload = json.dumps({"schema": 1, "mode": "offline", "delivery": delivery},
                         sort_keys=True, separators=(",", ":"))
    return f'<script type="application/json" id="okf-asset-bootstrap">{payload}</script>\n'


def _carrier(carrier_id: str, data: bytes, encode) -> str:
    return (f'<script type="application/json" id="{carrier_id}">'
            f'{encode(data.decode("utf-8"))}</script>')


def _notices_block(notices: str, licenses: tuple[tuple[str, str], ...],
                   extra: tuple[tuple[str, str], ...] = ()) -> str:
    text = notices.rstrip("\n") + "\n"
    for name, body in (*licenses, *extra):
        text += f"\n===== {name} =====\n{body.rstrip()}\n"
    lowered = text.lower()
    if "</script" in lowered or "<!--" in lowered:
        raise VendorIntegrityError("third-party notices cannot be embedded as plain text")
    return f'<script type="text/plain" id="okf-third-party-notices">\n{text}</script>'


def body_needs(data: Any) -> set[str]:
    """Which lazy renderers the embedded single-file bodies can trigger."""
    needs: set[str] = set()

    def walk(value: Any) -> None:
        if len(needs) == len(_BODY_NEEDS):
            return
        if isinstance(value, str):
            for need, pattern in _BODY_NEEDS:
                if need not in needs and pattern.search(value):
                    needs.add(need)
        elif isinstance(value, dict):
            for item in value.values():
                walk(item)
        elif isinstance(value, (list, tuple)):
            for item in value:
                walk(item)

    walk(data)
    return needs


def load_offline_assets(root: Path | None = None) -> OfflineAssets:
    """Read and verify every vendored file; raise before anything is written."""
    with VendorTree(root) as tree:
        return _load_offline_assets(tree)


def _load_offline_assets(tree: VendorTree) -> OfflineAssets:
    lock = _parse_lock(tree.read(LOCK_NAME))
    verified: dict[str, bytes] = {}
    entries = lock_files(lock)
    for entry in entries:
        dest = str(_safe_rel(entry.get("dest", "")))
        if dest in verified:
            raise VendorIntegrityError(f"vendored path listed twice: {dest}")
        data = tree.read(dest)
        _check_entry(entry, data)
        verified[dest] = data
    auxiliary: dict[str, tuple[str, bytes]] = {}
    for entry in auxiliary_files(lock):
        dest = str(_safe_rel(entry["dest"]))
        if dest in verified or dest in (LOCK_NAME, KATEX_DERIVED, HLJS_DERIVED):
            raise VendorIntegrityError(f"vendored path listed twice: {dest}")
        data = tree.read(dest)
        _check_entry(entry, data)
        auxiliary[dest] = (entry["role"], data)

    # The code's SRI pins are the reviewed authority for every file the CDN
    # mode also loads: the lock must agree with them, byte for byte.
    pins = source_sri_pins()
    by_cdn = {entry["cdn"]: entry for entry in entries if entry.get("cdn")}
    for url, integrity in pins.items():
        entry = by_cdn.get(url)
        if entry is None:
            raise VendorIntegrityError(f"no vendored copy for the pinned CDN asset {url}")
        if entry.get("sha384") != integrity or sri_sha384(verified[entry["dest"]]) != integrity:
            raise VendorIntegrityError(f"vendored copy does not match the code's SRI: {url}")
    chain: list[str] = []
    for url in cdn_graph_chain():
        entry = by_cdn.get(url)
        if entry is None:
            raise VendorIntegrityError(f"no vendored copy for the graph script {url}")
        chain.append(entry["dest"])

    # Derived outputs: pure transforms of verified inputs, pinned by hash.
    fonts = {
        rel[len(KATEX_FONT_DIR):-len(".woff2")]: data
        for rel, data in verified.items()
        if rel.startswith(KATEX_FONT_DIR) and rel.endswith(".woff2")
    }
    languages = [
        (rel, data) for rel, data in verified.items()
        if rel.startswith(HLJS_LANGUAGE_DIR) and rel.endswith(".min.js")
    ]
    try:
        _check_ledger_css(lock, verified)
        derived = {
            LEDGER_DERIVED: derive_ledger_css(verified),
            KATEX_DERIVED: derive_katex_css(verified[KATEX_CSS], fonts),
            HLJS_DERIVED: derive_hljs_bundle(verified[HLJS_CORE], languages),
        }
    except KeyError as exc:
        raise VendorIntegrityError(f"vendored input missing from the lock: {exc}") from exc
    pinned = lock.get("derived") or {}
    for rel, data in derived.items():
        expect = pinned.get(rel)
        if not isinstance(expect, dict) or expect.get("size") != len(data) \
                or expect.get("sha256") != sha256_hex(data):
            raise VendorIntegrityError(f"derived offline asset does not match its pinned hash: {rel}")

    files: dict[str, bytes] = {}
    for key, (path, _carrier_id) in RENDERER_ASSETS.items():
        rel = path[len(STATIC_VENDOR_DIR) + 1:]
        files[rel] = derived.get(rel, verified.get(rel))  # type: ignore[assignment]
        if files[rel] is None:
            raise VendorIntegrityError(f"offline renderer asset missing: {rel}")
    for rel in chain:
        files[rel] = verified[rel]
    licenses: list[tuple[str, str]] = []
    for package in lock["packages"]:
        for entry in package.get("files", []):
            if PurePosixPath(entry["dest"]).name == "LICENSE":
                files[entry["dest"]] = verified[entry["dest"]]
                licenses.append((f'{package["name"]}@{package["version"]}',
                                 verified[entry["dest"]].decode("utf-8")))
    texts: dict[str, str] = {}
    for dest, (role, data) in auxiliary.items():
        files[dest] = data
        if role == "notices":
            try:
                texts[dest] = data.decode("utf-8")
            except UnicodeDecodeError as exc:
                raise VendorIntegrityError(f"auxiliary notices file is not UTF-8: {dest}") from exc
    extra = tuple((dest, text) for dest, text in texts.items() if dest != NOTICES_NAME)
    return OfflineAssets(files=files, graph_chain=tuple(chain),
                         notices=texts[NOTICES_NAME], licenses=tuple(licenses),
                         extra_notices=extra)
